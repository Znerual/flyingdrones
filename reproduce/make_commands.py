#!/usr/bin/env python3
"""Print (or write) the exact evaluator command lines used for the paper.

``reproduce/manifest.tsv`` has one row per (checkpoint x resolution) cell of the
benchmark (264 cells + 3 zero-flow rows, protocol ``stratified``) plus the 51 cells of
the contiguous-window sensitivity study (protocol ``window500``, paper Appendix
"Sensitivity to the Sampling Protocol").

Every command is meant to be run from the root of the corresponding upstream checkout
(``$UPSTREAM``, see ``evaluators/<evaluator_dir>/README.md``) and uses four
environment variables:

    FD_DATA   directory that contains the ``Nature3/`` dataset folder
    FD_REPO   root of this repository (for the split files)
    FD_OUT    output directory (``summary/<tag>.csv`` and ``pairs/<tag>.csv``)
    CKPT      directory that holds the released checkpoints of that family

Examples::

    python reproduce/make_commands.py --family raft                # print RAFT cells
    python reproduce/make_commands.py --family raft --H 270        # one resolution
    python reproduce/make_commands.py --write-evaluator-scripts    # refresh evaluators/*/commands.sh
"""
import argparse
import collections
import os
import os.path as osp

HERE = osp.dirname(osp.abspath(__file__))
REPO = osp.dirname(HERE)


def read_manifest(path=osp.join(HERE, "manifest.tsv")):
    with open(path) as fh:
        lines = [l.rstrip("\n") for l in fh if l.strip()]
    hdr = lines[0].lstrip("#").split("\t")
    return [dict(zip(hdr, l.split("\t"))) for l in lines[1:] if not l.startswith("#")]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--family", help="manifest family key (raft, searaft, ..., zeroflow)")
    ap.add_argument("--protocol", choices=["stratified", "window500"], default=None)
    ap.add_argument("--H", type=int, default=None, help="only this evaluation height")
    ap.add_argument("--write-evaluator-scripts", action="store_true",
                    help="(re)write evaluators/<dir>/commands.sh for every family")
    a = ap.parse_args()
    rows = read_manifest()

    if a.write_evaluator_scripts:
        by_dir = collections.defaultdict(list)
        for r in rows:
            by_dir[r["evaluator_dir"]].append(r)
        for d, rs in by_dir.items():
            out = osp.join(REPO, "evaluators", d, "commands.sh")
            os.makedirs(osp.dirname(out), exist_ok=True)
            with open(out, "w") as fh:
                fh.write("#!/usr/bin/env bash\n")
                fh.write("# Generated by reproduce/make_commands.py from reproduce/manifest.tsv -- do not edit.\n")
                fh.write("# Run from the root of the upstream checkout (see README.md in this folder) with\n")
                fh.write("#   FD_DATA (contains Nature3/), FD_REPO (this repository), FD_OUT (results dir)\n")
                fh.write("#   and CKPT (directory with the released checkpoints) set.\n")
                fh.write("set -euo pipefail\n")
                fh.write(': "${FD_DATA:?}" "${FD_REPO:?}" "${FD_OUT:?}"\n')
                if any(r["ckpt"] != "-" for r in rs):
                    fh.write(': "${CKPT:?}"\n')
                fh.write('mkdir -p "$FD_OUT/summary" "$FD_OUT/pairs"\n')
                for proto in ("stratified", "window500"):
                    sel = [r for r in rs if r["protocol"] == proto]
                    if not sel:
                        continue
                    title = ("stratified 999-pair evaluation subset (main tables)" if proto == "stratified"
                             else "contiguous window, reference frames 0001-0500 (protocol-sensitivity table)")
                    fh.write(f"\n# ---- {title}\n")
                    for r in sel:
                        fh.write(f"\n# {r['tag']}\n{r['command']}\n")
            os.chmod(out, 0o755)
            print(f"wrote {osp.relpath(out, REPO)} ({len(rs)} commands)")
        return

    for r in rows:
        if a.family and r["family"] != a.family:
            continue
        if a.protocol and r["protocol"] != a.protocol:
            continue
        if a.H and int(r["H"]) != a.H:
            continue
        print(f"# {r['tag']}  (cd evaluators/{r['evaluator_dir']} upstream root)")
        print(r["command"])


if __name__ == "__main__":
    main()
